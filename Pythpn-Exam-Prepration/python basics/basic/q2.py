#2. Write a program to check whether a number is positive, negative, or zero.

def chk_number (num):

    if num > 0:
        print("Number is Positive")

    elif num < 0:
        print("Number Is Negative")

    elif num == 0 :
        print("Number is Zero") 

    else:print("Invalid Attempt")       

chk_number(1)    
